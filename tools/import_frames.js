// node tools/import_frames.js [GeometryDash.exe]  -> lib/objects_frames.js
//
// GD 2.2's own table of object id -> sprite frame name, read from the user's game binary (default:
// $GD_GAME/GeometryDash.exe, Steam path). GD builds it in ObjectToolbox's init as thousands of
//   mov dword [rbp+x], <id> ; ... ; lea rdx, [rip+"square_01_001.png"] ; call <string assign>
// so: every RIP-relative lea of a "*.png" string in .text, with the last `mov dword [..], imm32` in the
// 48 bytes before it as its id, in the one big run of them (the function). Only ids and frame names are
// kept (facts, like lib/objects_extra.js); no code or art. Checked against OpenGD's 2.1 table
// (tools/import_art.js): 1434 of 1541 ids give the same root frame; the rest are objects whose root
// sprite GD swaps in its setup (OpenGD's table has the swapped one, e.g. 40 plank -> colorPlank),
// so lib/art.js prefers OpenGD's entry where there is one. Re-run after a GD update.
const fs = require("fs"), path = require("path");
const GAME = process.env.GD_GAME || "C:/Program Files (x86)/Steam/steamapps/common/Geometry Dash";
const exe = process.argv[2] || path.join(GAME, "GeometryDash.exe");
const b = fs.readFileSync(exe);

const pe = b.readUInt32LE(0x3c), nsec = b.readUInt16LE(pe + 6), optsz = b.readUInt16LE(pe + 20), opt = pe + 24;
const secs = {};
for (let i = 0; i < nsec; i++) {
  const s = opt + optsz + i * 40, name = b.toString("ascii", s, s + 8).replace(/\0.*/, "");
  secs[name] = { va: b.readUInt32LE(s + 12), raw: b.readUInt32LE(s + 20), size: b.readUInt32LE(s + 16) };
}
const text = secs[".text"], rd = secs[".rdata"];
function pngAt(rva) {
  if (rva < rd.va || rva >= rd.va + rd.size) return null;
  const o = rva - rd.va + rd.raw, e = b.indexOf(0, o);
  if (e - o < 5 || e - o > 80) return null;
  const s = b.toString("latin1", o, e);
  return /^[\w.\-]+\.png$/.test(s) ? s : null;
}
const rows = [];
for (let o = text.raw; o < text.raw + text.size - 7; o++) {
  if ((b[o] !== 0x48 && b[o] !== 0x4c) || b[o + 1] !== 0x8d || (b[o + 2] & 0xc7) !== 0x05) continue;
  const s = pngAt(o - text.raw + text.va + 7 + b.readInt32LE(o + 3));
  if (!s) continue;
  let id = null;
  for (let k = o - 48; k < o; k++) {
    if (b[k] !== 0xc7) continue;
    let imm = null;
    if (b[k + 1] === 0x85) imm = b.readInt32LE(k + 6);                       // mov dword [rbp+disp32], imm32
    else if (b[k + 1] === 0x45) imm = b.readInt32LE(k + 3);                  // mov dword [rbp+disp8], imm32
    else if (b[k + 1] === 0x44 && b[k + 2] === 0x24) imm = b.readInt32LE(k + 4); // mov dword [rsp+disp8], imm32
    if (imm > 0 && imm < 10000) id = imm;
  }
  if (id != null) rows.push([o, id, s]);
}
// the biggest run of such pairs with gaps under 2 KB is ObjectToolbox's table
let runs = [], cur = null;
for (const r of rows) { if (!cur || r[0] - cur.end > 2000) runs.push(cur = { end: r[0], rows: [] }); cur.end = r[0]; cur.rows.push(r); }
const best = runs.sort((a, b) => b.rows.length - a.rows.length)[0];
const frames = {};
for (const [, id, s] of best.rows) if (!frames[id]) frames[id] = s;
// 914 is the text object (no sprite; drawn with GD's font): the pattern above gives it the start-pos
// button's frame (31's), so it is dropped here (showcase session, 2026-11-23)
delete frames[914];
const ids = Object.keys(frames).map(Number).sort((a, b) => a - b);
const sorted = {}; for (const id of ids) sorted[id] = frames[id];
const file = path.join(__dirname, "..", "lib", "objects_frames.js");
fs.writeFileSync(file, `// generated by tools/import_frames.js from GD 2.2's own object table -- do not edit.
// object id -> its root sprite frame (in GJ_GameSheet*.plist of the user's install). ${ids.length} ids, ${ids[0]}..${ids[ids.length - 1]}.
(function (GD) {
  GD.FRAMES = ${JSON.stringify(sorted)};
})(typeof module !== "undefined" ? module.exports : (window.GD = window.GD || {}));
`);
console.log("wrote", file, ids.length, "ids", ids[0] + ".." + ids[ids.length - 1]);
