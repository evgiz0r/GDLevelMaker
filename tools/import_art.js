// node tools/import_art.js <OpenGD checkout>  -> lib/objects_art.js
//
// Which sprite frames GD draws for each object id, taken as FACTS (frame names, offsets, colour roles,
// default z-layer / z-order / colour channels) from OpenGD (github.com/Open-GD/OpenGD, GPL, a GD 2.1
// reimplementation, commit 2a0e307): Content/Custom/object.json and GameObject::getGlowFrame in
// Source/GameObject.cpp. Only those numbers and names are kept, not OpenGD's code or file.
// Get it with:
//   git clone --depth 1 https://github.com/Open-GD/OpenGD.git   (then git checkout 2a0e307 if it moved)
// NOT used on purpose: GDRWeb (its README forbids use for AI level generation/modification, which is
// what this project does) and GDWeb (CC BY-NC-ND). See VISUALS.md "Sources".
//
// Format of GD.ART[id] = [zLayer, zOrder, ch1, ch2, type, frame, role, children]
//   zLayer: GD 2.1 values -3 B4, -1 B3, 1 B2, 3 B1, 5 T1, 7 T2, 9 T3 (GD 2.2 adds -5 B5 and 11 T4)
//   zOrder: default z order inside the layer; ch1/ch2: default main / detail colour channel (0 = none,
//   -1 = none for ch2); type: OpenGD's object_type; role: "b" base (main colour), "d" detail,
//   "k" black (channel 1010), "" untinted.
//   child = [frame, role, x, y, rot, scaleX, scaleY, flip (1 x, 2 y), z, anchorX, anchorY, contentW, contentH, children]
//   x, y are in the parent's points from its bottom-left corner (cocos2d), rot clockwise degrees,
//   z < 0 draws behind the parent. 1 point = 1 GD unit (uhd sheets are 4 px per point).
// GD.ART_GLOW[id] = glow frame (GJ_GameSheetGlow), drawn additively under the object.
const fs = require("fs"), path = require("path");
const root = process.argv[2];
if (!root) { console.error("usage: node tools/import_art.js <OpenGD checkout>"); process.exit(1); }
const json = JSON.parse(fs.readFileSync(path.join(root, "Content", "Custom", "object.json"), "utf8"));
const cpp = fs.readFileSync(path.join(root, "Source", "GameObject.cpp"), "utf8");

const ROLE = { base: "b", detail: "d", black: "k" };
const r3 = v => Math.round(v * 1000) / 1000;
function child(c) {
  const out = [c.texture_name, ROLE[c.color_channel] || "", r3(c.x), r3(c.y), r3(c.rot || 0), r3(c.scale_x), r3(c.scale_y),
    (c.flip_x ? 1 : 0) | (c.flip_y ? 2 : 0), c.z | 0, r3(c.anchor_x), r3(c.anchor_y),
    c.content_x == null ? null : r3(c.content_x), c.content_y == null ? null : r3(c.content_y)];
  if (c.children && c.children.length) out.push(c.children.map(child));
  return out;
}
const art = {};
for (const id of Object.keys(json).sort((a, b) => a - b)) {
  const o = json[id];
  const row = [o.default_z_layer, o.default_z_order, o.default_primary_channel, o.default_secondary_channel, o.object_type,
    o.texture_name, ROLE[o.color_channel] || ""];
  if (o.children && o.children.length) row.push(o.children.map(child));
  art[id] = row;
}
const glow = {};
const body = cpp.slice(cpp.indexOf("std::string_view GameObject::getGlowFrame"));
for (const m of body.slice(0, body.indexOf("\n}")).matchAll(/case\s+(\d+):\s*return\s*"([^"]+)"/g)) glow[m[1]] = m[2] + ".png";

const file = path.join(__dirname, "..", "lib", "objects_art.js");
fs.writeFileSync(file, `// generated by tools/import_art.js -- do not edit. Which sprite frames GD draws per object id
// (facts from OpenGD's object data, GD 2.1); format at the top of tools/import_art.js. No art here:
// the frames are drawn from the user's own game install at run time (lib/art.js, VISUALS.md).
(function (GD) {
  GD.ART = ${JSON.stringify(art)};
  GD.ART_GLOW = ${JSON.stringify(glow)};
})(typeof module !== "undefined" ? module.exports : (window.GD = window.GD || {}));
`);
console.log("wrote", file, Object.keys(art).length, "objects,", Object.keys(glow).length, "glow frames");
