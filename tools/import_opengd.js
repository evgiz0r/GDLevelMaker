// node tools/import_opengd.js <LongData.cpp>  -> lib/objects_extra.js
//
// Pulls the facts we need about every object -- solid / hazard / trigger, hitbox size, saw radius --
// out of OpenGD's object data (github.com/Open-GD/OpenGD, Source/LongData.cpp, commit 2a0e307,
// a reimplementation of GD 2.1). Only those numbers are kept, not their code or file.
// Get the file with:
//   curl -sSL -o LongData.cpp https://raw.githubusercontent.com/Open-GD/OpenGD/2a0e30793d86247ad5839a26a8f0ee586f9e84dd/Source/LongData.cpp
// Rule: an object with a hitbox that is not solid, not a trigger and not one of our own entries in
// lib/objects.js (portals, orbs, pads...) is a hazard. Objects with no hitbox are decoration.
const fs = require("fs");
const path = require("path");
const src = fs.readFileSync(process.argv[2], "utf8");

function block(name) {
  const i = src.indexOf(name);
  if (i < 0) throw new Error("no " + name);
  const open = src.indexOf("{", src.indexOf("=", i));
  let d = 0, j = open;
  for (; j < src.length; j++) { if (src[j] === "{") d++; else if (src[j] === "}") { d--; if (d === 0) break; } }
  return src.slice(open + 1, j);
}
const hit = {};
for (const m of block("_pHitboxes").matchAll(/\{\s*(\d+)\s*,\s*\{\s*([-\d.]+)\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)\s*\}\s*\}/g)) {
  // {height, width, left, bottom} relative to the object's centre
  const h = +m[2], w = +m[3], left = +m[4], bottom = +m[5];
  hit[m[1]] = { w, h, ox: +(left + w / 2).toFixed(3), oy: +(bottom + h / 2).toFixed(3) };
}
const radius = {};
for (const m of block("_pHitboxRadius").matchAll(/\{\s*(\d+)\s*,\s*([-\d.]+)\s*\}/g)) radius[m[1]] = +m[2];
const solids = new Set(block("_pSolids").match(/\d+/g).map(String));
const triggers = new Set(block("_pTriggers").match(/\d+/g).map(String));

const out = {};
const ids = new Set([...Object.keys(hit), ...Object.keys(radius), ...solids, ...triggers]);
for (const id of [...ids].sort((a, b) => a - b)) {
  if (triggers.has(id)) { out[id] = ["trigger"]; continue; }
  const h = hit[id];
  if (radius[id]) { out[id] = ["hazard", 0, 0, 0, 0, radius[id]]; continue; }
  if (!h) continue;
  out[id] = [solids.has(id) ? "solid" : "hazard", h.w, h.h, h.ox, h.oy];
}
const file = path.join(__dirname, "..", "lib", "objects_extra.js");
fs.writeFileSync(file, `// generated by tools/import_opengd.js -- do not edit.
// Facts about GD objects (kind, hitbox w, h, centre offset x, y, saw radius) taken from OpenGD's
// object data (GD 2.1). lib/objects.js entries win over these.
(function (GD) {
  GD.EXTRA = ${JSON.stringify(out)};
})(typeof module !== "undefined" ? module.exports : (window.GD = window.GD || {}));
`);
const counts = {};
for (const v of Object.values(out)) counts[v[0]] = (counts[v[0]] || 0) + 1;
console.log("wrote", file, counts);
