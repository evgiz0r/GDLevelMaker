#!/usr/bin/env node
// Usage: node tools/song_grids.js [--check]
// Beat grids kept in the repo: viewer/song_grids.js holds the numbers tools/beats.js measured from every song
// (bpm, period, t0, beats, downbeat, conf, sections), never the audio, so the viewer, the whiteboard, the phone
// page and the public site show bars, BPM and sections without the mp3. Merges local/beats.local.js into it
// (new measurements win, songs no longer on this PC are kept). tools/beats.js runs it after each index.
// --check: exit 1 when local/beats.local.js has a song the committed file lacks.
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, ".."), LOCAL = path.join(ROOT, "local", "beats.local.js"), OUT = path.join(ROOT, "viewer", "song_grids.js");
const read = f => { if (!fs.existsSync(f)) return {}; const w = {}; new Function("window", fs.readFileSync(f, "utf8"))(w); return w.SONG_GRIDS || w.GD_BEATS || {}; };
const KEEP = ["name", "bpm", "period", "t0", "beats", "downbeat", "conf", "sections", "dur"];
function merge() {
  const old = read(OUT), now = read(LOCAL), out = {};
  for (const [u, g] of Object.entries(Object.assign({}, old, now))) { const o = {}; for (const k of KEEP) if (g[k] != null) o[k] = g[k]; out[u] = o; }
  return { old, out };
}
function write() {
  const { old, out } = merge(), keys = Object.keys(out).sort();
  const body = keys.map(k => JSON.stringify(k) + ":" + JSON.stringify(out[k])).join(",\n");
  fs.writeFileSync(OUT, "// generated by tools/song_grids.js from tools/beats.js's measurements: numbers only, no audio (committed)\n" +
    "// Loaded after local/beats.local.js; fills in every song this page does not already know.\n" +
    "window.SONG_GRIDS = {\n" + body + "\n};\nwindow.GD_BEATS = Object.assign({}, window.SONG_GRIDS, window.GD_BEATS || {});\n");
  return { n: keys.length, added: keys.filter(k => !old[k]).length };
}
module.exports = { write, merge };
if (require.main === module) {
  if (process.argv.includes("--check")) { const { old, out } = merge(); const miss = Object.keys(out).filter(k => !old[k]); console.log(miss.length ? "missing: " + miss.join(" ") : "ok"); process.exit(miss.length ? 1 : 0); }
  const r = write(); console.log(`viewer/song_grids.js: ${r.n} songs (${r.added} new)`);
}
