// node tools/brickset.js [--check]   -- the whiteboard's brick set: every verified, non-empty lego piece of OUR levels
// (knowledge/lego.json, src "ours") with its gameplay objects, route and presses, as viewer/bricks.js (window.GD_BRICKS).
// Only our own levels: RobTop's bricks never go into the repo or onto the phone page (LEGO.md "Where the catalogue lives").
// Used by lib/intent.js (the one-pen board: a drawn path is filled with bricks, a drawn shape snaps to one; DRAW.md
// "One pen: path or shape"). Evgeni's 👎 votes (knowledge/lego_votes.json) leave a brick out.
"use strict";
const fs = require("fs"), path = require("path");
const { GD, readGdlvl } = require("./io.js");
const ROOT = path.join(__dirname, ".."), OUT = path.join(ROOT, "viewer", "bricks.js");
const PLAY = new Set(["solid", "slope", "hazard", "orb", "pad", "mode", "gravity", "speed", "size"]);
const r1 = v => Math.round(v * 10) / 10;

function build() {
  const K = JSON.parse(fs.readFileSync(path.join(ROOT, "knowledge", "lego.json"), "utf8"));
  let votes = {}; try { votes = JSON.parse(fs.readFileSync(path.join(ROOT, "knowledge", "lego_votes.json"), "utf8")).votes || {}; } catch (e) {}
  const down = id => { const v = votes[id]; return v && (v.down || 0) > (v.up || 0); };
  const levels = {}, runs = {}, out = [];
  global.window = global.window || {}; require(path.join(ROOT, "viewer", "levels.js"));
  const sol = {}; for (const L of window.GD_LEVELS) if (L.solution && L.solution.events) sol[L.file] = L.solution.events;
  const runOf = (file, lv) => {   // the level's saved route replayed: the player's centre per tick, in blocks
    if (runs[file] !== undefined) return runs[file];
    const ev = sol[file]; if (!ev) return (runs[file] = null);
    const q = GD.run(GD.makeWorld(lv.objects, lv.header), ev);
    return (runs[file] = q.dead ? null : q.path.map(s => [GD.progressX ? GD.progressX(s) : s.x, s.y]));
  };
  for (const p of K.pieces) {
    if (p.src !== "ours" || !p.verified || p.empty || !/^levels\//.test(p.file || "") || down(p.id)) continue;
    if (!levels[p.file]) { try { levels[p.file] = readGdlvl(path.join(ROOT, p.file)).level; } catch (e) { levels[p.file] = null; } }
    const lv = levels[p.file]; if (!lv) continue;
    const x0 = p.x * 30, x1 = (p.x + p.w) * 30, objs = [];
    for (const o of lv.objects) {
      if (o.x < x0 || o.x >= x1) continue;
      const k = (GD.objInfo(o.id) || {}).kind; if (!PLAY.has(k)) continue;
      const q = [o.id, r1(o.x - x0), r1(o.y)];
      if (o.rot || o.flipX || o.flipY) q.push(o.rot || 0, o.flipX ? 1 : 0, o.flipY ? 1 : 0);
      objs.push(q);
    }
    if (!objs.length || objs.length > 400) continue;
    const run = runOf(p.file, lv); if (!run) continue;
    const path_ = []; let last = -1;
    for (const [x, y] of run) if (x >= x0 && x < x1 && x - x0 >= last + 15) { last = x - x0; path_.push([r1(last / 30), r1(y / 30)]); }   // a point every half block
    if (path_.length < 4) continue;
    out.push({ id: p.id, mode: p.mode, sp: p.speed, w: p.w, wrap: p.wrap, sig: p.sig, en: p.entry, ex: p.exit, path: path_,
      clicks: (p.clicks || []).map(c => [c[0], c[2]]), objs, tight: p.tightMs, diff: p.diff });
  }
  return out;
}
function write() {
  const b = build(), s = "// generated by tools/brickset.js from knowledge/lego.json (our levels only) -- do not edit\nwindow.GD_BRICKS = " + JSON.stringify(b) + ";\n";
  fs.writeFileSync(OUT, s); return { n: b.length, kb: Math.round(s.length / 1024) };
}
module.exports = { build, write };
if (require.main === module) {
  if (process.argv.includes("--check")) { const now = fs.existsSync(OUT) && fs.readFileSync(OUT, "utf8"), b = build(); console.log(now && now.includes(JSON.stringify(b)) ? "bricks.js current" : "bricks.js STALE: run node tools/brickset.js"); }
  else { const r = write(); console.log(`viewer/bricks.js: ${r.n} bricks, ${r.kb} KB`); }
}
