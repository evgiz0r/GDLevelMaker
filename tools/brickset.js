// node tools/brickset.js --main [pieces.json]   -- the main levels' bricks (RobTop's) for Evgeni's PRIVATE pages only ->
//   local/bricks_main.js (window.GD_BRICKS_MAIN). Never committed, never on the public site (the user, 2026-11-25: main-level
//   bricks OK on his private claude.ai pages). Built from local/lego/pieces.json (or the private catalogue's pieces.json):
//   each piece's hitbox boxes become objects again (a box -> the object whose hitbox it is), its route and presses kept.
//   tools/web.js and tools/draw_web.js copy it when it exists; the board uses it after viewer/bricks.js.
// node tools/brickset.js [--check]   -- the whiteboard's brick set: every verified, non-empty lego piece of OUR levels
// (knowledge/lego.json, src "ours") with its gameplay objects, route and presses, as viewer/bricks.js (window.GD_BRICKS).
// Only our own levels: RobTop's bricks never go into the repo or onto the phone page (LEGO.md "Where the catalogue lives").
// Used by lib/intent.js (the one-pen board: a drawn path is filled with bricks, a drawn shape snaps to one; DRAW.md
// "One pen: path or shape"). Evgeni's 👎 votes (knowledge/lego_votes.json) leave a brick out.
"use strict";
const fs = require("fs"), path = require("path");
const { GD, readGdlvl } = require("./io.js");
const ROOT = path.join(__dirname, ".."), OUT = path.join(ROOT, "viewer", "bricks.js");
const PLAY = new Set(["solid", "slope", "hazard", "orb", "pad", "mode", "gravity", "speed", "size"]);
const r1 = v => Math.round(v * 10) / 10;

function build() {
  const K = JSON.parse(fs.readFileSync(path.join(ROOT, "knowledge", "lego.json"), "utf8"));
  let votes = {}; try { votes = JSON.parse(fs.readFileSync(path.join(ROOT, "knowledge", "lego_votes.json"), "utf8")).votes || {}; } catch (e) {}
  const down = id => { const v = votes[id]; return v && (v.down || 0) > (v.up || 0); };
  const levels = {}, runs = {}, out = [];
  global.window = global.window || {}; require(path.join(ROOT, "viewer", "levels.js"));
  const sol = {}; for (const L of window.GD_LEVELS) if (L.solution && L.solution.events) sol[L.file] = L.solution.events;
  const runOf = (file, lv) => {   // the level's saved route replayed: the player's centre per tick, in blocks
    if (runs[file] !== undefined) return runs[file];
    const ev = sol[file]; if (!ev) return (runs[file] = null);
    const q = GD.run(GD.makeWorld(lv.objects, lv.header), ev);
    return (runs[file] = q.dead ? null : q.path.map(s => [GD.progressX ? GD.progressX(s) : s.x, s.y]));
  };
  for (const p of K.pieces) {
    if (p.src !== "ours" || !p.verified || p.empty || !/^levels\//.test(p.file || "") || down(p.id)) continue;
    if (!levels[p.file]) { try { levels[p.file] = readGdlvl(path.join(ROOT, p.file)).level; } catch (e) { levels[p.file] = null; } }
    const lv = levels[p.file]; if (!lv) continue;
    const x0 = p.x * 30, x1 = (p.x + p.w) * 30, objs = [];
    for (const o of lv.objects) {
      if (o.x < x0 || o.x >= x1) continue;
      const k = (GD.objInfo(o.id) || {}).kind; if (!PLAY.has(k)) continue;
      const q = [o.id, r1(o.x - x0), r1(o.y)];
      if (o.rot || o.flipX || o.flipY) q.push(o.rot || 0, o.flipX ? 1 : 0, o.flipY ? 1 : 0);
      objs.push(q);
    }
    if (!objs.length || objs.length > 400) continue;
    const run = runOf(p.file, lv); if (!run) continue;
    const path_ = []; let last = -1;
    for (const [x, y] of run) if (x >= x0 && x < x1 && x - x0 >= last + 15) { last = x - x0; path_.push([r1(last / 30), r1(y / 30)]); }   // a point every half block
    if (path_.length < 4) continue;
    out.push({ id: p.id, mode: p.mode, sp: p.speed, w: p.w, wrap: p.wrap, sig: p.sig, en: p.entry, ex: p.exit, path: path_,
      clicks: (p.clicks || []).map(c => [c[0], c[2]]), objs, tight: p.tightMs, diff: p.diff });
  }
  return out;
}
function write() {
  const b = build(), s = "// generated by tools/brickset.js from knowledge/lego.json (our levels only) -- do not edit\nwindow.GD_BRICKS = " + JSON.stringify(b) + ";\n";
  fs.writeFileSync(OUT, s); return { n: b.length, kb: Math.round(s.length / 1024) };
}
// ---- the main levels (private) ----
const COLOUR_ID = {};   // (kind letter, colour) -> object id, from lib/objects.js's colours
(function () {
  const L = { orb: "O", pad: "P", mode: "M", gravity: "G", speed: "V", size: "Z" };
  for (let id = 0; id < 4000; id++) { const o = GD.objInfo(id); if (!o || !o.color || !L[o.kind]) continue; const k = L[o.kind] + o.color; if (COLOUR_ID[k] == null) COLOUR_ID[k] = id; }
})();
const HAZ = [8, 9, 39, 61, 88, 89, 98, 178, 205].map(id => { const h = (GD.objInfo(id) || {}).hit; return h && { id, w: h.w / 30, h: h.h / 30 }; }).filter(Boolean);
const SLOPE = { "/": {}, "\\": { flipX: 1 }, "7": { flipY: 1 }, r: { flipX: 1, flipY: 1 } };
function boxObjects(shape) {
  const out = [], put = (id, x, y, f) => { const q = [id, r1(x * 30), r1(y * 30)]; f = f || {}; if (f.rot || f.flipX || f.flipY) q.push(f.rot || 0, f.flipX ? 1 : 0, f.flipY ? 1 : 0); out.push(q); };
  for (const [k, x0, y0, x1, y1, col, corner] of shape) {
    const cx = (x0 + x1) / 2, cy = (y0 + y1) / 2, w = x1 - x0, h = y1 - y0;
    if (k === "S") {   // solid: block cells, a slab where it is half a block high
      if (h < 0.75) { for (let x = x0; x < x1 - 0.25; x += 1) put(40, x + Math.min(1, x1 - x) / 2, cy); continue; }
      for (let x = x0; x < x1 - 0.25; x += 1) for (let y = y0; y < y1 - 0.25; y += 1) put(1, x + 0.5, y + 0.5);
    } else if (k === "L") put(1338, cx, cy, SLOPE[corner] || {});
    else if (k === "H") {
      let best = null;
      for (const z of HAZ) for (const rot of [0, 90]) { const hw = rot ? z.h : z.w, hh = rot ? z.w : z.h, e = Math.abs(hw - w) + Math.abs(hh - h); if (!best || e < best.e) best = { id: z.id, rot, e }; }
      put(best.id, cx, cy, { rot: best.rot });
    } else { const id = COLOUR_ID[k + col]; if (id != null) put(id, cx, cy); }
  }
  return out;
}
function parse(v) { if (typeof v !== "string") return v; try { return JSON.parse(v); } catch (e) {} try { return JSON.parse(v.replace(/'/g, '"').replace(/\bNone\b/g, "null").replace(/\bTrue\b/g, "true").replace(/\bFalse\b/g, "false")); } catch (e) { return null; } }
function buildMain(file) {
  const all = JSON.parse(fs.readFileSync(file, "utf8")), out = [];
  for (const p of all) {
    if (p.src !== "official" || String(p.verified) !== "True" && p.verified !== true || String(p.empty) === "True" || p.empty === true) continue;
    const shape = parse(p.shape), pth = parse(p.path), clicks = parse(p.clicks); const w = +p.w;
    if (!shape || !shape.length || !pth || pth.length < 4 || !(w >= 6 && w <= 40)) continue;
    const objs = boxObjects(shape.filter(b => b[1] >= -0.01 && b[1] < w)); if (!objs.length || objs.length > 500) continue;
    const path_ = []; let last = -1; for (const [x, y] of pth) if (x >= last + 0.5) { last = x; path_.push([r1(x), r1(y)]); }
    const st = (a, b) => ({ mode: p.mode, sp: +p.speed || 1, grav: 1, y: a[1], ground: Math.abs(a[1] - b[1]) < 0.05 && Math.abs((a[1] - 0.5) % 1) < 0.05 });
    out.push({ id: p.id, mode: p.mode, sp: +p.speed || 1, w, wrap: p.wrap, sig: p.sig, en: st(pth[0], pth[1]), ex: st(pth[pth.length - 1], pth[pth.length - 2]),
      path: path_, clicks: (clicks || []).map(c => [c[0], c[2]]), objs, main: 1 });
  }
  return out;
}
module.exports = { build, write, buildMain, boxObjects };
if (require.main === module) {
  if (process.argv.includes("--main")) {
    const f = process.argv[process.argv.indexOf("--main") + 1], src = f && !f.startsWith("--") ? f : path.join(ROOT, "local", "lego", "pieces.json");
    const b = buildMain(src), out = path.join(ROOT, "local", "bricks_main.js");
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, "// the main levels' bricks: RobTop's layouts, PRIVATE pages only (never git, never the public site)\nwindow.GD_BRICKS_MAIN = " + JSON.stringify(b) + ";\n");
    console.log(`local/bricks_main.js: ${b.length} bricks (private)`);
  } else if (process.argv.includes("--check")) { const now = fs.existsSync(OUT) && fs.readFileSync(OUT, "utf8"), b = build(); console.log(now && now.includes(JSON.stringify(b)) ? "bricks.js current" : "bricks.js STALE: run node tools/brickset.js"); }
  else { const r = write(); console.log(`viewer/bricks.js: ${r.n} bricks, ${r.kb} KB`); }
}
