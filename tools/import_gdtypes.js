// node tools/import_gdtypes.js <object_types.gen.hpp>  -> lib/objects_gd22.js
//
// Which object ids GD 2.2 itself builds as pure decoration (no collision at all), as gdsolver
// (github.com/gdsolver/gdsolver, MIT, src/mod/object_types.gen.hpp) read them off the game's own
// object exports of 1,039 levels. Only the id ranges are kept. lib/objects.js uses them to
// overrule the 2.1-era OpenGD table, which calls some decoration hazards (Theory of Everything 2's
// and Dash's background shapes 1020 / 1888 killed the sim before this).
const fs = require("fs"), path = require("path");
const t = fs.readFileSync(process.argv[2], "utf8");
const ranges = s => [...s.matchAll(/\{(\d+), (\d+)\}/g)].map(m => [+m[1], +m[2]]);
const dec = ranges(t.slice(t.indexOf("kDecoration[]"), t.indexOf("kTrigger[]")));
const out = `// Generated by tools/import_gdtypes.js from gdsolver's object_types.gen.hpp (MIT) -- do not edit.
// GD 2.2's decoration ids (no collision), as [lo, hi] ranges.
(function (GD) { GD.DECO22 = ${JSON.stringify(dec)}; })(typeof module !== "undefined" ? module.exports : (window.GD = window.GD || {}));
`;
fs.writeFileSync(path.join(__dirname, "..", "lib", "objects_gd22.js"), out);
console.log(dec.length + " ranges");
